"""Ф5 добор genre — образец локализации записей в томе (сессия g5, v4/v5).
Нормализованный поиск: игла и стог через ОДНУ norm-функцию (гомоглифы лат→кир,
0→О, °→О, Ё→Е, Й→И, удаление всей пунктуации и пробелов — ловит внутрисловные
разрывы). После g5 добавлена замена °→О (ловушка «В Н°ЧЬ», «Г°АА»).
Использование: python3 g5_locate.py <vol> [cat] [ctx]  — при наличии <vol>_lines.json
рядом (получить через f5_extract_lines.py). TARGETS заполняется под сессию."""
import json, re, sys

LAT2CYR = str.maketrans({
    'A':'А','B':'В','C':'С','E':'Е','H':'Н','K':'К','M':'М','O':'О','P':'Р',
    'T':'Т','X':'Х','Y':'У','I':'1','L':'Л','D':'Д','N':'П','U':'И','R':'Г',
    'a':'а','b':'ь','c':'с','e':'е','h':'н','k':'к','m':'м','o':'о','p':'р',
    'x':'х','y':'у','u':'и','n':'п','r':'г','t':'т','i':'і','d':'д','l':'л',
    'Ё':'Е','ё':'е','Й':'И','й':'и',
})

def norm(s):
    s = s.upper().translate(LAT2CYR)
    s = s.replace('Ё','Е').replace('Й','И')
    s = s.replace('0','О').replace('°','О')   # гомоглифы «О»: ноль и знак градуса
    s = re.sub(r'[^А-ЯІ0-9]', '', s)          # снять пунктуацию/пробелы/лат-остатки
    return s

def load(vol):
    return json.load(open(f'{vol}_lines.json', encoding='utf-8'))

def locate(lines, needle_norm):
    """Индексы строк с нормализованной иглой + склейки соседних строк (разрыв титула)."""
    hits = []
    nl = [norm(t) for _, t, _ in lines]
    for i, s in enumerate(nl):
        if needle_norm and needle_norm in s:
            hits.append(('line', i))
    for i in range(len(nl) - 1):
        j2 = nl[i] + nl[i+1]
        if needle_norm in j2 and not (needle_norm in nl[i] or needle_norm in nl[i+1]):
            hits.append(('join2', i))
    return hits

