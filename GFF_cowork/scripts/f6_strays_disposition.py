_lines = {}
def L(vol, n):
    if vol not in _lines:
        _lines[vol] = json.load(open(f"work/{vol.split('_')[0]}_lines.json", encoding='utf-8'))
    row = _lines[vol][n]
    assert row[0] == n, (vol, n, row[0])
    return row[1]

def join_lines(vol, nums):
    """Склейка печатных строк: перенос «-» на конце строки склеивается без пробела, иначе — пробел.
    Ведущие маркеры-«буллеты» (". ", "•") и хвостовые табуляции снимаются механически."""
    out = ''
    for n in nums:
        t = L(vol, n).strip()
        t = re.sub(r'^[.•\s]+', '', t)
        t = re.sub(r'[\t•\s]+$', '', t)
        if out.endswith('-') and re.match(r'^[а-яё]', t):
            out = out[:-1] + t
        else:
            out = (out + ' ' + t) if out else t
    return out.strip()

def endp(s):
    return s if re.search(r'[.!?…»)]$', s) else s + '.'

def norm(s):
    s = (s or '').lower().replace('ё', 'е')
    return re.sub(r'\s+', ' ', re.sub(r'[^а-яa-z0-9 ]+', ' ', s)).strip()

def coverage(stray_i, target_i):
    a, b = norm(cat[stray_i]['annotation']), norm(cat[target_i]['annotation'])
    sm = difflib.SequenceMatcher(None, a, b, autojunk=False)
    m = sum(bl.size for bl in sm.get_matching_blocks() if bl.size >= 40)
    return round(m / max(1, len(b)), 3), round(m / max(1, len(a)), 3)

def sim(a, b):
    a, b = norm(a), norm(b)
    return round(difflib.SequenceMatcher(None, a, b, autojunk=False).ratio(), 3)

