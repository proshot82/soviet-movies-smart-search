def rec(i, cls, verdict, target=None, vol=None, lines=None, note=''):
    r = cat[i]; a = al[i]
    d = {'cat': i, 'title': r['title'], 'source': r['source'], 'method': a['method'], 'f4_group': a['f4_group'],
         'class': cls, 'verdict': verdict, 'target': target, 'vol': vol, 'lines': lines, 'note': note}
    if target is not None:
        d['target_title'] = cat[target]['title']
        d['target_xlsx_row'] = al[target]['xlsx_row']
        d['target_num'] = al[target]['idx_num']
        assert target not in S, ('целевая запись — страй', target)
    disp[i] = d
    if verdict.startswith('delete'):
        actions['delete'].append(i)
    return d

