def restore(target, vol, lines, text, cls_note, from_strays):
    before = cat[target]['annotation']
    assert text and text != before
    for marker in (r'Авт\. сцен', r'(^|[;,] )реж\.', r'(^|[;,] )опер\.', r'звукоопер', r'В ролях', r'Библиография', r'Роли дублируют', r'дир\. картины'):
        assert not re.search(marker, text), (target, marker)
    actions['restore'][target] = {'field': 'annotation', 'before': before, 'after': text, 'vol': vol, 'lines': lines,
                                  'class': 'restore', 'from_strays': from_strays, 'note': cls_note}

