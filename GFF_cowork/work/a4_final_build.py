# restores (crew-only записи; проза из томов)
def full(vname, idxs):
    L = json.load(open(f'work/{vname}_lines.json', encoding='utf-8'))
    parts = [L[j][1].strip() for j in idxs]
    out = parts[0]
    for p in parts[1:]:
        out = (out[:-1] + p) if out.endswith('-') else (out + ' ' + p)
    return re.sub(r'\s+', ' ', out).strip()
R = {}
def rst(c, v, idxs, note='проза статьи (аннотация состояла из обрывка титров)'):
    R[str(c)] = {'text': full(v, idxs), 'vol': v, 'lines': idxs, 'note': note}
