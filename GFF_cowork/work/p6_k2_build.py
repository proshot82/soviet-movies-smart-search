# -*- coding: utf-8 -*-
"""k2: канон studio — кавычки бренд-имён (quotes) + лексика/пунктуация (lex/punct)."""
import json, re, collections
cat = json.load(open('state/catalog_f5_k1.json', encoding='utf-8'))
al = json.load(open('state/alignment_v17.json', encoding='utf-8'))
S = {a['cat_pos'] for a in al if a.get('xlsx_row') is None}

PAT = re.compile(r'^«([^«»]+)»(\s+им\.\s+[^«»()]+?)?(\s*\([^()«»]*\))?$')
EXCL_NAMES = {'Русь', 'Буревестник'}
def quotes_target(s):
    m = PAT.match(s)
    if not m: return None
    name = m.group(1).strip()
    if name in EXCL_NAMES: return None
    if not re.search(r'(фильм|филм)$', name): return None
    par = m.group(3) or ''
    if re.search(r'при участии|при содействии|совм', par): return None
    return re.sub(r'[«»]', '', s)

