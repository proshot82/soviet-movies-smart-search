PUNCT = {
 'Центральная киностудия детских и юношеских фильмов им. М. Горького, Ялтинский филиал': 'Центральная киностудия детских и юношеских фильмов им. М. Горького (Ялтинский филиал)',
 'Центральная киностудия детских и юношеских фильмов им. М. Горького, (Ялтинский филиал)': 'Центральная киностудия детских и юношеских фильмов им. М. Горького (Ялтинский филиал)',
 'Госкино, Л.': 'Госкино (Л.)',
 'Севзапкино, М.': 'Севзапкино (М.)',
}
SET = {}
for i, r in enumerate(cat):
    if i in S or not r['studio']: continue
    s = r['studio']
    if s in LEX:
        SET[str(i)] = {'field': 'studio', 'before': s, 'after': LEX[s], 'vol': r['source'].split('_')[0], 'line': None,
                       'class': 'lex', 'note': 'вариант одного имени → доминирующая внутрикаталожная форма (решение владельца 02.09.2026); печатная форма = before'}
    elif s in PUNCT:
        SET[str(i)] = {'field': 'studio', 'before': s, 'after': PUNCT[s], 'vol': r['source'].split('_')[0], 'line': None,
                       'class': 'punct', 'note': 'пунктуационный вариант → доминирующая форма; печатная форма = before'}
    else:
        t = quotes_target(s)
        if t:
            SET[str(i)] = {'field': 'studio', 'before': s, 'after': t, 'vol': r['source'].split('_')[0], 'line': None,
                           'class': 'quotes', 'note': 'канон П6: бренд-имя студии без кавычек (решение владельца 02.09.2026); печатная форма = before'}
res = {'set': SET, 'confirm': {}, 'dict': {'lex': sorted(set(LEX.values())), 'punct': sorted(set(PUNCT.values()))}}
json.dump(res, open('scripts/k2_resolution.json', 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
print('SET', len(SET), collections.Counter(v['class'] for v in SET.values()))
pairs = collections.Counter((v['before'], v['after']) for v in SET.values())
for (b, a), n in sorted(pairs.items(), key=lambda x: -x[1]): print(f"{n:5d}  {b!r} → {a!r}")
