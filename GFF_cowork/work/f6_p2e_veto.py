# -*- coding: utf-8 -*-
import json, os, re
res = json.load(open('scripts/f6_p2e_resolution.json', encoding='utf-8'))
san = json.load(open('scripts/_f6_p2e_sanction.json', encoding='utf-8')) if os.path.exists('scripts/_f6_p2e_sanction.json') else None
cand = {(r['cat'], r['word']): r for r in json.load(open('work/f6_p2d_cand.json', encoding='utf-8'))}
def esc(s): return s.replace('|', '\\|').replace('\n', '⏎')
def q(s): return '«' + esc(s) + '»'
L = ['# ВЕТО Ф6-П2е — буквенные OCR-ошибки внутри слов аннотаций (auto-строки списка кандидатов)\n',
     f'Вход: `state/catalog_f6_p2d.json` (7173). Выход: `state/catalog_f6_p2e.json` (7173; удалений 0; правится ТОЛЬКО поле `annotation`). '
     f'Список кандидатов: `veto/П2д_кандидаты_OCR_буквы.xlsx` (генератор `work/f6_p2d_cand.py`); резолюция: `work/f6_p2e_build.py` → '
     f'`scripts/f6_p2e_resolution.json`; apply: `scripts/f6_apply_p2e.py`; приёмка: `scripts/f6_p2e_check.py`; протокол применённого: `scripts/_f6_p2e_sanction.json`.\n']
if san: L.append(f'Применено: {san["_meta"]["applied"]}; результат: `{json.dumps(san["_meta"]["result"], ensure_ascii=False)}`.\n')
m = res['_meta']['counts']
L += ['## §0. Сводка и правило\n',
      f'- Строк auto=да в списке: **{m["auto_rows"]}**; применено **{m["applied_auto"]}** (в {m["records"]} записях); исключено после ручного просмотра всех auto-строк: **{m["excluded"]}** (§2); ручных вариантов: **{m["manual"]}** (§3).',
      '- Правило auto (подтверждено владельцем 02.09.2026): слово вне словаря pymorphy3 (строчное, ≥4 букв, без дефиса), ровно один словарный кандидат на расстоянии одной правки '
      '(замена/вставка/удаление/перестановка) или разрыва на два слова; искажённая форма встречается в корпусе 1 раз; и либо правка — типичная OCR-пара с кандидатом, '
      'встречающимся в корпусе ≥1 раз, либо кандидат встречается ≥3 раз, либо разрыв склеенных слов с однобуквенным предлогом/союзом, глагольной формой или местоимением; '
      'плюс «склейка» — два соседних слова вне словаря, слитно дающие словарное слово (потерян дефис переноса).',
      '- Строки auto=нет (1890) и без кандидата (930) НЕ применялись — остаются в xlsx на решение владельца (или на второй проход с ручной оценкой).',
      '- Alignment/мастер/реестр — без содержательных изменений; титулы/годы/студии/жанры — без изменений (И5′). Инварианты И1′–И6 в apply.\n',
      '## §1. Применённые правки — полный список\n',
      '| cat | название | том | было | стало | правка | кандидат в корпусе | контекст |\n|---|---|---|---|---|---|---|---|']
for x in res['set']:
    for o in x['ops']:
        if o[0] != 'O': continue
        r = cand[(x['cat'], o[1])]
        L.append(f'| {x["cat"]} | {esc(x["title"])} | {x["vol"]} | {q(o[1])} | {q(o[2])} | {esc(o[3])} | {r["freq_candidate"]} | {esc(r["context"])} |')
L += ['', '## §2. Исключено из auto после просмотра (НЕ применено)\n', '| cat | слово | кандидат списка | причина |\n|---|---|---|---|']
for e in res['excluded']:
    L.append(f'| {e["cat"]} | {q(e["word"])} | {q(e["candidate"])} | {esc(e["reason"])} |')
L += ['', '## §3. Ручные варианты (вместо auto-кандидата)\n', '| cat | название | было | стало | основание |\n|---|---|---|---|---|']
for x in res['set']:
    for o in x['ops']:
        if o[0] == 'M': L.append(f'| {x["cat"]} | {esc(x["title"])} | {q(o[1])} | {q(o[2])} | {esc(o[4])} |')
L += ['', '## §4. Что осталось (к сведению)\n',
      '- В xlsx: auto=нет — 1890 строк (кандидат есть, но правило не выполнено: несколько кандидатов, редкая правка, слово с прописной); без кандидата — 930 '
      '(редкие/иноязычные/сильно искажённые слова, в т. ч. cat3631 «Наш дом»). Второй проход возможен только с ручной оценкой каждой строки.',
      '- Заметные остатки в исправленных записях, не подпавшие под правило: cat2324 «канцеляриоа», cat2453 «инс грументов», cat1460 «На 1 сьезде» (→ «I»), cat1648 «бейиы», «врах а», «паши части».\n']
os.makedirs('veto', exist_ok=True)
open('veto/ВЕТО_Ф6_П2е.md', 'w', encoding='utf-8').write('\n'.join(L))
print('veto:', len(L), 'строк;', os.path.getsize('veto/ВЕТО_Ф6_П2е.md') // 1024, 'KB')
